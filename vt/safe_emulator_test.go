// TestSafeEmulatorLocksEveryMethod fails when a method of Emulator reaches a
// SafeEmulator through the embedding, and so without the lock.
func TestSafeEmulatorLocksEveryMethod(t *testing.T) {
	// InputPipe returns a pipe that is safe by itself, and that never changes.
	unlocked := map[string]bool{"InputPipe": true}

	safe := reflect.TypeOf(&SafeEmulator{})
	for i := range safe.NumMethod() {
		m := safe.Method(i)
		if unlocked[m.Name] {
			continue
		}
		// The compiler writes the wrapper of a promoted method itself.
		pc := m.Func.Pointer()
		if file, _ := runtime.FuncForPC(pc).FileLine(pc); file == "<autogenerated>" {
			t.Errorf("SafeEmulator.%s is not declared in safe_emulator.go, so it does not lock", m.Name)
		}
	}
}

// TestSafeEmulatorConcurrent calls the methods of a SafeEmulator from many
// goroutines at once. It asserts nothing: it is the race detector that fails
// it.
func TestSafeEmulatorConcurrent(t *testing.T) {
	se := NewSafeEmulator(80, 24)

	drained := make(chan struct{})
	go func() {
		defer close(drained)
		_, _ = io.Copy(io.Discard, se)
	}()

	// What a program writes, to touch the state that each method reads: the
	// modes, the default colors, the logger and the handlers.
	output := strings.Join([]string{
		"hello\r\n",
		"\x1b[6n",                    // a reply on the input pipe
		"\x1b[?1004h\x1b[?1004l",     // focus events, for Focus and Blur
		"\x1b[?1h\x1b[?1l",           // cursor keys, for SendKey and SendKeys
		"\x1b[?2027h\x1b[?2027l",     // unicode core, for WidthMethod
		"\x1b]10;?\x07\x1b]11;?\x07", // the default colors
		"\x1b]12;?\x07",              // the default cursor color
		"\x1b[y\x1b]7777;x\x07\x1by", // the handlers registered below
		"\x1b[?99999h",               // an unknown mode, for the logger
	}, "")

	calls := []func(){
		func() { _, _ = se.Write([]byte(output)) },
		func() { _, _ = se.WriteString(output) },
		func() { _ = se.String() },
		func() { _ = se.Render() },
		func() { _ = se.Bounds() },
		func() { _ = se.WidthMethod() },
		func() { _ = se.CursorPosition() },
		func() { se.Resize(100, 30) },
		func() { se.SendText("a") },
		func() { se.SendKey(KeyPressEvent{Code: KeyEnter}) },
		func() { se.SendKeys(KeyPressEvent{Code: KeyUp}, KeyPressEvent{Code: KeyDown}) },
		func() { se.Paste("pasted") },
		func() { se.Focus() },
		func() { se.Blur() },
		func() { se.SetDefaultForegroundColor(nil) },
		func() { se.SetDefaultBackgroundColor(nil) },
		func() { se.SetDefaultCursorColor(nil) },
		func() { se.SetCallbacks(Callbacks{}) },
		func() { se.SetLogger(nil) },
		func() { se.RegisterCsiHandler('y', func(ansi.Params) bool { return false }) },
		func() { se.RegisterOscHandler(7777, func([]byte) bool { return false }) },
		func() { se.RegisterEscHandler('y', func() bool { return false }) },
	}

	var wg sync.WaitGroup
	for _, call := range calls {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for range 50 {
				call()
			}
		}()
	}
	wg.Wait()

	if err := se.Close(); err != nil {
		t.Fatalf("close: %v", err)
	}
	<-drained
}

func TestSafeEmulatorClose(t *testing.T) {
	t.Run("ends a Read that waits for input", func(t *testing.T) {
		se := NewSafeEmulator(80, 24)

		read := make(chan error, 1)
		go func() {
			_, err := se.Read(make([]byte, 1))
			read <- err
		}()

		if err := se.Close(); err != nil {
			t.Fatalf("close: %v", err)
		}
		select {
		case err := <-read:
			if !errors.Is(err, io.EOF) {
				t.Fatalf("read: got %v, want EOF", err)
			}
		case <-time.After(5 * time.Second):
			t.Fatal("Read did not return after Close")
		}
	})

	t.Run("ends a send that nothing reads", func(t *testing.T) {
		se := NewSafeEmulator(80, 24)

		sent := make(chan struct{})
		go func() {
			defer close(sent)
			se.SendText("never read")
		}()
		// SendText holds the lock for as long as it waits for a reader.
		for se.mu.TryLock() {
			se.mu.Unlock()
			runtime.Gosched()
		}

		// Close runs apart from the test, so that one that waits for the lock
		// fails here, and not at the timeout of the whole run.
		closed := make(chan error, 1)
		go func() { closed <- se.Close() }()
		select {
		case err := <-closed:
			if err != nil {
				t.Fatalf("close: %v", err)
			}
		case <-time.After(5 * time.Second):
			t.Fatal("Close did not return while a send holds the lock")
		}
		select {
		case <-sent:
		case <-time.After(5 * time.Second):
			t.Fatal("SendText did not return after Close")
		}
	})

	t.Run("is safe to call more than once, and from many goroutines", func(t *testing.T) {
		se := NewSafeEmulator(80, 24)

		var wg sync.WaitGroup
		for range 8 {
			wg.Add(1)
			go func() {
				defer wg.Done()
				if err := se.Close(); err != nil {
					t.Errorf("close: %v", err)
				}
			}()
		}
		wg.Wait()

		if _, err := se.Read(make([]byte, 1)); !errors.Is(err, io.EOF) {
			t.Fatalf("read after close: got %v, want EOF", err)
		}
		if _, err := se.Write([]byte("x")); !errors.Is(err, io.ErrClosedPipe) {
			t.Fatalf("write after close: got %v, want ErrClosedPipe", err)
		}
	})
}
